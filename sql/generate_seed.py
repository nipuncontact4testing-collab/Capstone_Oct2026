"""Generate sql/seed_data.sql from the three CSVs in data/.

Why a generator instead of `.import`?
  The sqlite3 shell's `.import` into an existing table loads the header row as
  data and loads blank cells as empty strings, not NULL. Plain INSERT
  statements avoid both pitfalls and run in any SQLite client.

Blank CSV cells -> NULL. Nothing is hand-typed: the file is rebuilt from the CSVs.
Usage:  python sql/generate_seed.py
"""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
OUT = ROOT / "sql" / "seed_data.sql"

# (table, csv file, columns, integer columns, real columns)
TABLES = [
    ("customers", "customers.csv",
     ["customer_id", "name", "city", "city_tier", "signup_date", "acquisition_source"],
     {"city_tier"}, set()),
    ("products", "products.csv",
     ["product_id", "product_name", "category", "price"],
     set(), {"price"}),
    ("orders", "orders.csv",
     ["order_id", "customer_id", "product_id", "order_date", "quantity",
      "discount_pct", "payment_method", "rating", "returned"],
     {"quantity", "discount_pct", "rating", "returned"},
     set()),
]


def literal(value, col, ints, reals):
    value = value.strip()
    if value == "":
        return "NULL"
    if col in ints:
        return str(int(value))
    if col in reals:
        return repr(float(value))
    return "'" + value.replace("'", "''") + "'"


def main():
    lines = [
        "-- =====================================================================",
        "-- seed_data.sql  |  Part 1, Task 2: load the three CSVs",
        "-- AUTO-GENERATED by sql/generate_seed.py from data/*.csv (do not hand-edit).",
        "-- Blank CSV cells are loaded as NULL. Re-runnable: tables are emptied first.",
        "-- Run AFTER schema.sql.",
        "-- =====================================================================",
        "PRAGMA foreign_keys = ON;",
        "",
        "DELETE FROM orders;",
        "DELETE FROM products;",
        "DELETE FROM customers;",
        "",
    ]
    for table, fname, cols, ints, reals in TABLES:
        with open(DATA / fname, newline="", encoding="utf-8") as fh:
            rows = list(csv.DictReader(fh))
        lines.append(f"-- {table}: {len(rows)} rows")
        for r in rows:
            vals = ", ".join(literal(r[c], c, ints, reals) for c in cols)
            lines.append(f"INSERT INTO {table} ({', '.join(cols)}) VALUES ({vals});")
        lines.append("")
    lines += [
        "-- Verification: expected row counts 45 / 16 / 180",
        "SELECT 'customers' AS table_name, COUNT(*) AS row_count FROM customers",
        "UNION ALL SELECT 'products', COUNT(*) FROM products",
        "UNION ALL SELECT 'orders',   COUNT(*) FROM orders;",
        "",
        "-- Verification: blanks must be NULL, never empty strings (expect 0 / 0)",
        "SELECT SUM(discount_pct = '') AS empty_string_discounts,",
        "       SUM(rating = '')       AS empty_string_ratings",
        "FROM orders;",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
